"""Rebuild bundled gettext catalogs: python scripts/build_translations.py.

Sources are locale/ui/<language>.json. No network calls.
The small djangojs domain contains strings used by the chat and market clients.
"""
import ast
import json
import hashlib
import importlib.util
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def build():
    source = json.loads((ROOT / 'locale/ui/en.json').read_text())
    catalogs = {p.stem: json.loads(p.read_text()) for p in (ROOT / 'locale/ui').glob('*.json') if p.stem != 'en'}
    for code, catalog in catalogs.items():
        if source.keys() - catalog.keys() or not all(catalog.get(key) for key in source):
            raise ValueError(f'Incomplete translation catalog: {code}')
    # Public language packs make the same translations available to the offline shell.
    public = ROOT / 'static/i18n'
    public.mkdir(exist_ok=True)
    spec = importlib.util.spec_from_file_location('language_registry', ROOT / 'accounts/languages.py')
    registry = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(registry)
    labels = dict(registry.LANGUAGE_CHOICES)
    published = {'en': source, **catalogs}
    languages = []
    digest = hashlib.sha256()
    for code, messages in sorted(published.items()):
        payload = json.dumps(messages, ensure_ascii=False, sort_keys=True)
        (public / f'{code}.json').write_text(payload + '\n')
        digest.update((code + payload).encode())
        languages.append({'code': code, 'label': labels[code], 'dir': 'rtl' if code in registry.RTL_LANGUAGES else 'ltr'})
    (public / 'manifest.json').write_text(json.dumps({'version': digest.hexdigest()[:16], 'languages': languages}, ensure_ascii=False, indent=2) + '\n')
    rows = source
    client = (ROOT / 'static/js/chat.js').read_text()
    client += (ROOT / 'static/js/mandi.js').read_text()
    js_keys = {ast.literal_eval(m.group(1)) for m in re.finditer(r'''\b(?:gettext|t)\(("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')\)''', client)}
    missing = js_keys - rows.keys()
    if missing:
        raise ValueError(f'Missing client translations: {missing}')
    for code, catalog in catalogs.items():
        folder = ROOT / 'locale' / code / 'LC_MESSAGES'
        folder.mkdir(parents=True, exist_ok=True)
        for domain in ('django', 'djangojs'):
            header = f'Project-Id-Version: Krishi Mitra\nLanguage: {code}\nMIME-Version: 1.0\nContent-Type: text/plain; charset=UTF-8\nContent-Transfer-Encoding: 8bit\nPlural-Forms: nplurals=2; plural=(n != 1);\n'
            entries = ['# Generated by scripts/build_translations.py; edit locale/ui/<language>.json.', 'msgid ""', 'msgstr ' + json.dumps(header), '']
            for source in sorted(rows):
                if domain == 'djangojs' and source not in js_keys:
                    continue
                entries += ['msgid ' + json.dumps(source, ensure_ascii=False),
                            'msgstr ' + json.dumps(catalog[source], ensure_ascii=False), '']
            path = folder / (domain + '.po')
            path.write_text('\n'.join(entries), encoding='utf-8')
            subprocess.run(['msgfmt', '--check', '-o', str(path.with_suffix('.mo')), str(path)], check=True, capture_output=True)
    print(f'Built {len(rows)} UI messages and {len(js_keys)} client messages in {len(catalogs)} languages.')


if __name__ == '__main__':
    build()
